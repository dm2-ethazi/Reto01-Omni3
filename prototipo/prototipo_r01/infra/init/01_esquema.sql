CREATE DATABASE IF NOT EXISTS hogwarts CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE hogwarts;

CREATE TABLE IF NOT EXISTS estudiantes (
  id INT NOT NULL AUTO_INCREMENT,
  nombre VARCHAR(120) NOT NULL,
  casa VARCHAR(40) NOT NULL,
  origen VARCHAR(20) NOT NULL,
  sincronizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_estudiantes (nombre, casa, origen)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE USER IF NOT EXISTS 'r01'@'%' IDENTIFIED BY 'r01';
GRANT ALL PRIVILEGES ON hogwarts.* TO 'r01'@'%';
FLUSH PRIVILEGES;
