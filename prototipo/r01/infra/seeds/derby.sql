    ID INT PRIMARY KEY,
    DNI VARCHAR(9) NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    CASA VARCHAR(30) NOT NULL,
    PATRONUS VARCHAR(50) NOT NULL,
    CONSTRAINT UQ_DERBY_DNI UNIQUE (DNI)
