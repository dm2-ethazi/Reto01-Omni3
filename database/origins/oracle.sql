CREATE TABLE ALUMNOS (
    ID VARCHAR2(64) PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    APELLIDO VARCHAR2(100),
    SEXO CHAR(1),
    PATRONUS VARCHAR2(100),
    IMAGEN VARCHAR2(500),
    CASA VARCHAR2(30),
    ALIAS VARCHAR2(2000),
    ESPECIE VARCHAR2(200),
    GENERO VARCHAR2(100),
    NACIMIENTO VARCHAR2(200),
    NACIONALIDAD VARCHAR2(200),
    WIKI VARCHAR2(500)
);
