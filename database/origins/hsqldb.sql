CREATE TABLE ALUMNOS (
    ID VARCHAR(64) PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    APELLIDO VARCHAR(100),
    SEXO CHAR(1),
    PATRONUS VARCHAR(100),
    IMAGEN VARCHAR(500),
    CASA VARCHAR(30),
    ALIAS VARCHAR(2000),
    ESPECIE VARCHAR(200),
    GENERO VARCHAR(100),
    NACIMIENTO VARCHAR(200),
    NACIONALIDAD VARCHAR(200),
    WIKI VARCHAR(500)
);
